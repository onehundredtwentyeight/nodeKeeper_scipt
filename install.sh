    cat <<EOF
remnainstall / nodeKeeper Installer v${INSTALLER_VERSION}

Usage:
  bash install.sh [OPTIONS]
  curl -fsSL <URL>/install.sh | bash
  curl -fsSL <URL>/install.sh | bash -s -- --config /path/to/nodekeeper.conf --yes

Options:
  -c, --config <path|url>   Load configuration from local file or remote URL
  -y, --yes, --unattended   Run non-interactively without confirmation prompts
      --mode <mode>         Install mode: basic | selfsteal-single | selfsteal-multi
      --hostname <name>     Full server hostname
      --domain <domain>     Selfsteal domain name
      --cf-token <token>    Cloudflare API Token (for selfsteal-multi)
      --panel-ip <ip>       Remnawave Panel IPv4 address
      --node-port <port>    Remnanode port (default: 2222)
      --secret-key <key>    Remnanode SECRET_KEY
      --user <username>     Admin username to create (default: node)
      --password <pass>     Admin password (default: autogenerated)
      --ssh-key "<pubkey>"  SSH public key for the new user
      --skip-checks         Skip pre-flight IP region and censorship checks
      --no-warp             Skip Cloudflare WARP installation
      --dry-run             Validate configuration and preview actions without modifying system
  -h, --help                Show this help message
EOF
}

parse_args() {
    while [ $# -gt 0 ]; do
        case "$1" in
            -c|--config)
                CONFIG_SOURCE="${2:-}"
                shift 2
                ;;
            -y|--yes|--unattended|--non-interactive)
                UNATTENDED="true"
                shift
                ;;
            --mode)
                INSTALL_MODE="${2:-}"
                shift 2
                ;;
            --hostname)
                NODE_HOSTNAME="${2:-}"
                shift 2
                ;;
            --domain)
                SELF_STEAL_DOMAIN="${2:-}"
                shift 2
                ;;
            --cf-token)
                CLOUDFLARE_API_TOKEN="${2:-}"
                shift 2
                ;;
            --panel-ip)
                PANEL_IP="${2:-}"
                shift 2
                ;;
            --node-port)
                NODE_PORT="${2:-2222}"
                shift 2
                ;;
            --secret-key)
                SECRET_KEY="${2:-}"
                shift 2
                ;;
            --user)
                ADMIN_USER="${2:-node}"
                shift 2
                ;;
            --password)
                ADMIN_PASSWORD="${2:-}"
                shift 2
                ;;
            --ssh-key)
                SSH_PUBLIC_KEY="${2:-}"
                shift 2
                ;;
            --skip-checks)
                RUN_IP_CHECKS="false"
                shift
                ;;
            --no-warp)
                INSTALL_WARP="false"
                shift
                ;;
            --dry-run)
                DRY_RUN="true"
                shift
                ;;
            -h|--help)
                show_usage
                exit 0
                ;;
            *)
                err "Unknown argument: $1"
                show_usage
                exit 1
                ;;
        esac
    done
}

load_config_source() {
    [ -z "$CONFIG_SOURCE" ] && return 0
    if [[ "$CONFIG_SOURCE" =~ ^https?:// ]]; then
        info "Fetching remote configuration from ${CONFIG_SOURCE}..."
        local tmp_cfg
        tmp_cfg=$(mktemp)
        if curl -fsSL "$CONFIG_SOURCE" -o "$tmp_cfg"; then
            # shellcheck disable=SC1090
            source "$tmp_cfg"
            rm -f "$tmp_cfg"
            ok "Remote configuration loaded."
        else
            rm -f "$tmp_cfg"
            err "Failed to download config from ${CONFIG_SOURCE}"
            exit 1
        fi
    elif [ -f "$CONFIG_SOURCE" ]; then
        info "Loading configuration from ${CONFIG_SOURCE}..."
        # shellcheck disable=SC1090
        source "$CONFIG_SOURCE"
        ok "Configuration file loaded."
    else
        err "Configuration file not found: ${CONFIG_SOURCE}"
        exit 1
    fi
}

# Safe interactive read that works even when script is piped via `curl ... | bash`
tty_read() {
    local prompt="$1"
    local var_name="$2"
    local default_val="${3:-}"
    local input=""

    if [ -r /dev/tty ]; then
        read -rp "$prompt" input < /dev/tty
    else
        read -rp "$prompt" input
    fi

    if [ -z "$input" ] && [ -n "$default_val" ]; then
        printf -v "$var_name" '%s' "$default_val"
    else
        printf -v "$var_name" '%s' "$input"
    fi
}

generate_password() {
    openssl rand -base64 32 2>/dev/null | LC_ALL=C tr -dc 'A-Za-z0-9' | head -c 20
}

detect_ssh_port() {
    local port=""
    if [ -f /etc/ssh/sshd_config ]; then
        port=$(awk '/^[[:space:]]*Port[[:space:]]+[0-9]+/ {print $2; exit}' /etc/ssh/sshd_config 2>/dev/null || true)
    fi
    echo "${port:-22}"
}

detect_root_ssh_key() {
    if [ -f /root/.ssh/authorized_keys ]; then
        grep -E '^(ssh-(rsa|ed25519)|ecdsa-sha2-)' /root/.ssh/authorized_keys 2>/dev/null | head -n 1 || true
    fi
}

validate_ipv4() {
    local ip="$1"
    if [[ "$ip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then
        local IFS='.'
        read -r -a octets <<< "$ip"
        for o in "${octets[@]}"; do
            if [ "$o" -gt 255 ] 2>/dev/null; then
                return 1
            fi
        done
        return 0
    fi
    return 1
}

# ==============================================================================
# Step 1: Collect All Parameters Up Front
# ==============================================================================
collect_parameters() {
    echo -e "\n${C_BOLD}╭────────────────────────────────────────────────────────────────────╮${C_RESET}"
    echo -e "${C_BOLD}│       Remnawave Node Installer & nodeKeeper v${INSTALLER_VERSION}               │${C_RESET}"
    echo -e "${C_BOLD}╰────────────────────────────────────────────────────────────────────╯${C_RESET}"

    [ -z "$SSH_PORT" ] && SSH_PORT=$(detect_ssh_port)
    [ -z "$ADMIN_PASSWORD" ] && ADMIN_PASSWORD=$(generate_password)

    local detected_key
    detected_key=$(detect_root_ssh_key)

    if [ "$UNATTENDED" = "true" ]; then
        info "Running in unattended mode."
        [ -z "$NODE_HOSTNAME" ] && NODE_HOSTNAME=$(hostname)
        [ -z "$INSTALL_MODE" ] && INSTALL_MODE="basic"
        [ -z "$SSH_PUBLIC_KEY" ] && SSH_PUBLIC_KEY="$detected_key"
    else
        echo -e "${C_GRAY}Please enter all deployment parameters once. The installation will then run completely unattended.${C_RESET}\n"

        # 1. Hostname
        while [ -z "$NODE_HOSTNAME" ]; do
            tty_read "1. Enter full node hostname (e.g. kvn-msk10 / fin-node-01) [$(hostname)]: " NODE_HOSTNAME "$(hostname)"
        done

        # 2. Install Mode
        if [ -z "$INSTALL_MODE" ]; then
            echo -e "\n${C_BOLD}2. Select Remnanode Installation Mode:${C_RESET}"
            echo "   1) basic            — Remnanode only (no Caddy reverse proxy)"
            echo "   2) selfsteal-single — Remnanode + Caddy (one server per domain, HTTP-01)"
            echo "   3) selfsteal-multi  — Remnanode + Caddy with Cloudflare DNS plugin (multi-server)"
            local mode_choice=""
            while true; do
                tty_read "   Select mode [1-3, default 3]: " mode_choice "3"
                case "$mode_choice" in
                    1|basic)            INSTALL_MODE="basic"; break ;;
                    2|selfsteal-single) INSTALL_MODE="selfsteal-single"; break ;;
                    3|selfsteal-multi)  INSTALL_MODE="selfsteal-multi"; break ;;
                    *) warn "Please choose 1, 2, or 3." ;;
                esac
            done
        fi

        # 3. Domain & Cloudflare Token
        if [ "$INSTALL_MODE" = "selfsteal-single" ] || [ "$INSTALL_MODE" = "selfsteal-multi" ]; then
            while [ -z "$SELF_STEAL_DOMAIN" ]; do
                tty_read "3. Enter Selfsteal Domain (e.g. node.example.com): " SELF_STEAL_DOMAIN
            done
        fi

        if [ "$INSTALL_MODE" = "selfsteal-multi" ]; then
            while [ -z "$CLOUDFLARE_API_TOKEN" ]; do
                tty_read "4. Enter Cloudflare API Token (with Zone.DNS:Edit permission): " CLOUDFLARE_API_TOKEN
            done
        fi

        # 4. Panel IP & Node Port
        while ! validate_ipv4 "$PANEL_IP"; do
            tty_read "5. Enter Remnawave Panel IPv4 address (for port whitelist): " PANEL_IP
            validate_ipv4 "$PANEL_IP" || warn "Invalid IPv4 address format."
        done

        tty_read "6. Enter Remnanode port [${NODE_PORT}]: " NODE_PORT "$NODE_PORT"

        # 5. Remnanode SECRET_KEY
        while [ -z "$SECRET_KEY" ]; do
            tty_read "7. Paste Remnanode SECRET_KEY from Panel: " SECRET_KEY
            # Strip surrounding quotes/spaces if any
            SECRET_KEY=$(echo "$SECRET_KEY" | tr -d '[:space:]"')
        done

        # 6. Hardening User & Password & SSH Key
        echo -e "\n${C_BOLD}--- System Hardening Parameters ---${C_RESET}"
        tty_read "8. New sudo/docker username [${ADMIN_USER}]: " ADMIN_USER "$ADMIN_USER"

        local custom_pass=""
        tty_read "9. Password for '${ADMIN_USER}' [Enter to use auto-generated: ${ADMIN_PASSWORD}]: " custom_pass "$ADMIN_PASSWORD"
        ADMIN_PASSWORD="$custom_pass"

        if [ -z "$SSH_PUBLIC_KEY" ]; then
            if [ -n "$detected_key" ]; then
                echo -e "   Detected existing SSH key in /root/.ssh/authorized_keys:"
                echo -e "   ${C_CYAN}${detected_key:0:65}...${C_RESET}"
                tty_read "10. Paste SSH public key for '${ADMIN_USER}' [Enter to use detected key]: " SSH_PUBLIC_KEY "$detected_key"
            else
                while [ -z "$SSH_PUBLIC_KEY" ]; do
                    tty_read "10. Paste SSH public key for '${ADMIN_USER}' (required to disable password SSH): " SSH_PUBLIC_KEY
                done
            fi
        fi

        # 7. WARP & Maintenance
        echo -e "\n${C_BOLD}--- Additional Components ---${C_RESET}"
        local warp_ans=""
        tty_read "11. Install Cloudflare WARP automatically? [Y/n]: " warp_ans "Y"
        [[ "$warp_ans" =~ ^[Nn]$ ]] && INSTALL_WARP="false" || INSTALL_WARP="true"

        local maint_ans=""
        tty_read "12. Enable automated OS & container maintenance cron? [Y/n]: " maint_ans "Y"
        [[ "$maint_ans" =~ ^[Nn]$ ]] && MAINT_ENABLED="false" || MAINT_ENABLED="true"
    fi

    # Normalize mode names
    case "$INSTALL_MODE" in
        1|basic|no-caddy)                   INSTALL_MODE="basic" ;;
        2|single|selfsteal|selfsteal-single) INSTALL_MODE="selfsteal-single" ;;
        3|multi|cloudflare|selfsteal-multi)  INSTALL_MODE="selfsteal-multi" ;;
        *) err "Invalid INSTALL_MODE: $INSTALL_MODE"; exit 1 ;;
    esac

    # Validate required fields
    if [ "$INSTALL_MODE" != "basic" ] && [ -z "$SELF_STEAL_DOMAIN" ]; then
        err "SELF_STEAL_DOMAIN is required for mode ${INSTALL_MODE}."
        exit 1
    fi
    if [ "$INSTALL_MODE" = "selfsteal-multi" ] && [ -z "$CLOUDFLARE_API_TOKEN" ]; then
        err "CLOUDFLARE_API_TOKEN is required for mode selfsteal-multi."
        exit 1
    fi
    if [ -z "$SECRET_KEY" ]; then
        err "SECRET_KEY is required."
        exit 1
    fi

    # Show Pre-flight Parameter Summary
    echo -e "\n${C_BOLD}====================================================================${C_RESET}"
    echo -e "${C_BOLD}                  DEPLOYMENT CONFIGURATION SUMMARY                  ${C_RESET}"
    echo -e "${C_BOLD}====================================================================${C_RESET}"
    echo -e "  Hostname:            ${C_CYAN}${NODE_HOSTNAME}${C_RESET}"
    echo -e "  Install Mode:        ${C_CYAN}${INSTALL_MODE}${C_RESET}"
    [ -n "$SELF_STEAL_DOMAIN" ] && echo -e "  Selfsteal Domain:    ${C_CYAN}${SELF_STEAL_DOMAIN}${C_RESET}"
    [ "$INSTALL_MODE" = "selfsteal-multi" ] && echo -e "  Cloudflare Token:    ${C_CYAN}${CLOUDFLARE_API_TOKEN:0:8}***${C_RESET}"
    echo -e "  Panel IP Whitelist:  ${C_CYAN}${PANEL_IP}${C_RESET} (Node Port: ${NODE_PORT})"
    echo -e "  Admin User:          ${C_CYAN}${ADMIN_USER}${C_RESET}"
    echo -e "  Admin Password:      ${C_YELLOW}${ADMIN_PASSWORD}${C_RESET}"
    echo -e "  SSH Key Configured:  ${C_CYAN}$([ -n "$SSH_PUBLIC_KEY" ] && echo "Yes" || echo "No")${C_RESET}"
    echo -e "  SSH Port:            ${C_CYAN}${SSH_PORT}${C_RESET}"
    echo -e "  Cloudflare WARP:     ${C_CYAN}${INSTALL_WARP}${C_RESET}"
    echo -e "  Auto-Maintenance:    ${C_CYAN}${MAINT_ENABLED}${C_RESET} (${MAINT_MIN_DAYS}-${MAINT_MAX_DAYS} days)"
    echo -e "${C_BOLD}====================================================================${C_RESET}"

    if [ "$DRY_RUN" = "true" ]; then
        ok "Dry-run mode enabled. Configuration is valid. No system changes were made."
        exit 0
    fi

    if [ "$UNATTENDED" != "true" ]; then
        local confirm_go=""
        tty_read "Press [Enter] to run IP checks and begin unattended installation (or Ctrl+C to abort): " confirm_go ""
    fi
}

# ==============================================================================
# Step 2: Base Dependencies & Pre-Flight IP Checks
# ==============================================================================
run_preflight_checks() {
    step "1/8 Preparing Base Packages & Running Pre-flight IP Diagnostics"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y curl wget sudo ca-certificates cron gnupg lsb-release ufw

    mkdir -p "$NK_DIR" "$NK_LOG_DIR"
    local diag_log="${NK_LOG_DIR}/initial_diagnostics_$(date +%Y-%m-%d_%H-%M).log"

    if [ "$RUN_IP_CHECKS" = "true" ]; then
        info "Running IP region and censorship checks (logging to ${diag_log})..."
        echo "=== Initial IP Region & Censorship Check ($(date)) ===" > "$diag_log"
        wget -qO - "https://raw.githubusercontent.com/vernette/ipregion/refs/heads/master/ipregion.sh" | bash | tee -a "$diag_log" || warn "ipregion check returned non-zero"
        wget -qO - "https://github.com/vernette/censorcheck/raw/master/censorcheck.sh" | bash | tee -a "$diag_log" || warn "censorcheck returned non-zero"
        ok "Pre-flight diagnostics completed."
    else
        info "Skipping pre-flight IP checks (RUN_IP_CHECKS=false)."
    fi
}

# ==============================================================================
# Step 3: Hostname & Global OS Upgrade
# ==============================================================================
configure_system_and_hostname() {
    step "2/8 Setting Hostname & Updating System Packages"
    info "Setting hostname to '${NODE_HOSTNAME}'..."
    hostnamectl set-hostname "$NODE_HOSTNAME" || echo "$NODE_HOSTNAME" > /etc/hostname
    if ! grep -q "$NODE_HOSTNAME" /etc/hosts 2>/dev/null; then
        echo "127.0.1.1 ${NODE_HOSTNAME}" >> /etc/hosts
    fi
    ok "Hostname set to: $(hostname)"

    info "Running non-interactive system upgrade..."
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get upgrade -y -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold"
    ok "System packages updated."
}

# ==============================================================================
# Step 4: Install BBR, Fail2ban, and Docker
# ==============================================================================
install_core_tools() {
    step "3/8 Installing BBR, Fail2ban, and Docker"

    # BBR
    info "Enabling TCP BBR congestion control..."
    cat > /etc/sysctl.d/99-nodekeeper-bbr.conf <<'EOF'
net.core.default_qdisc=fq
net.ipv4.tcp_congestion_control=bbr
EOF
    sysctl --system >/dev/null 2>&1 || sysctl -p /etc/sysctl.d/99-nodekeeper-bbr.conf >/dev/null 2>&1 || true
    ok "BBR enabled (current: $(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null || echo 'bbr'))."

    # Fail2ban for SSH
    info "Installing and configuring Fail2ban for SSH..."
    apt-get install -y fail2ban
    mkdir -p /etc/fail2ban/jail.d
    cat > /etc/fail2ban/jail.d/sshd.local <<EOF
[sshd]
enabled = true
port = ${SSH_PORT}
filter = sshd
maxretry = 5
findtime = 10m
bantime = 1h
ignoreip = 127.0.0.1/8 ::1 ${PANEL_IP}
EOF
    systemctl enable fail2ban >/dev/null 2>&1 || true
    systemctl restart fail2ban >/dev/null 2>&1 || true
    ok "Fail2ban installed and protecting SSH on port ${SSH_PORT}."

    # Docker
    if ! command -v docker >/dev/null 2>&1; then
        info "Installing Docker Engine..."
        curl -fsSL https://get.docker.com | sh
    else
        info "Docker is already installed."
    fi
    systemctl enable --now docker >/dev/null 2>&1 || true
    ok "Docker is active ($(docker --version 2>/dev/null || echo 'installed'))."
}

# ==============================================================================
# Step 5: System Hardening (User, Sudo, Docker Group, SSH Keys, SSHD Config)
# ==============================================================================
harden_system() {
    step "4/8 Hardening System & Configuring User '${ADMIN_USER}'"

    if id "$ADMIN_USER" >/dev/null 2>&1; then
        info "User '${ADMIN_USER}' already exists. Updating groups and password..."
    else
        info "Creating user '${ADMIN_USER}'..."
        useradd -m -s /bin/bash "$ADMIN_USER"
    fi

    echo "${ADMIN_USER}:${ADMIN_PASSWORD}" | chpasswd
    usermod -aG sudo,docker "$ADMIN_USER"

    # Ensure sudo works cleanly
    cat > "/etc/sudoers.d/90-nodekeeper-${ADMIN_USER}" <<EOF
${ADMIN_USER} ALL=(ALL:ALL) ALL
EOF
    chmod 440 "/etc/sudoers.d/90-nodekeeper-${ADMIN_USER}"

    # Configure SSH public key
    local user_home
    user_home=$(eval echo "~${ADMIN_USER}")
    mkdir -p "${user_home}/.ssh"
    chmod 700 "${user_home}/.ssh"
    touch "${user_home}/.ssh/authorized_keys"

    if [ -n "$SSH_PUBLIC_KEY" ]; then
        if ! grep -Fq "$SSH_PUBLIC_KEY" "${user_home}/.ssh/authorized_keys" 2>/dev/null; then
            echo "$SSH_PUBLIC_KEY" >> "${user_home}/.ssh/authorized_keys"
        fi
    elif [ -f /root/.ssh/authorized_keys ]; then
        cat /root/.ssh/authorized_keys >> "${user_home}/.ssh/authorized_keys"
    fi

    chmod 600 "${user_home}/.ssh/authorized_keys"
    chown -R "${ADMIN_USER}:${ADMIN_USER}" "${user_home}/.ssh"

    # Harden SSH daemon only if at least one authorized key is present for ADMIN_USER
    if [ -s "${user_home}/.ssh/authorized_keys" ]; then
        info "Hardening SSH configuration (disabling root login and password authentication)..."
        mkdir -p /etc/ssh/sshd_config.d
        cat > /etc/ssh/sshd_config.d/99-nodekeeper-hardening.conf <<'EOF'
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
ChallengeResponseAuthentication no
PubkeyAuthentication yes
EOF
        # Also update main /etc/ssh/sshd_config in case Include directive isn't first
        sed -i 's/^[[:space:]]*#\?[[:space:]]*PermitRootLogin.*/PermitRootLogin no/' /etc/ssh/sshd_config
        sed -i 's/^[[:space:]]*#\?[[:space:]]*PasswordAuthentication.*/PasswordAuthentication no/' /etc/ssh/sshd_config
        sed -i 's/^[[:space:]]*#\?[[:space:]]*PubkeyAuthentication.*/PubkeyAuthentication yes/' /etc/ssh/sshd_config

        if sshd -t 2>/dev/null; then
            systemctl reload ssh >/dev/null 2>&1 || systemctl reload sshd >/dev/null 2>&1 || true
            ok "SSH hardened: Root login disabled, password login disabled, SSH key auth enforced."
        else
            warn "sshd -t reported a warning; reverting sshd drop-in to avoid lockout."
            rm -f /etc/ssh/sshd_config.d/99-nodekeeper-hardening.conf
        fi
    else
        warn "No SSH public key found in ${user_home}/.ssh/authorized_keys! Keeping password authentication enabled to prevent lockout."
    fi
}

# ==============================================================================
# Step 6: Automatic Non-Interactive Cloudflare WARP Installation
# ==============================================================================
install_warp_unattended() {
    step "5/8 Installing Cloudflare WARP (Unattended Native WireGuard)"
    if [ "$INSTALL_WARP" != "true" ]; then
        info "Skipping WARP installation (INSTALL_WARP=${INSTALL_WARP})."
        return 0
    fi

    if ip link show warp >/dev/null 2>&1 && [ -f /etc/wireguard/warp.conf ]; then
        ok "WARP interface is already installed and active."
        return 0
    fi

    apt-get install -y wireguard wireguard-tools

    local arch
    arch=$(uname -m)
    local wgcf_arch="amd64"
    case "$arch" in
        x86_64|amd64) wgcf_arch="amd64" ;;
        aarch64|arm64) wgcf_arch="arm64" ;;
        *) warn "Unsupported architecture for wgcf: $arch. Skipping WARP."; return 0 ;;
    esac

    info "Downloading wgcf (${wgcf_arch})..."
    local wgcf_url=""
    wgcf_url=$(curl -fsSL https://api.github.com/repos/ViRb3/wgcf/releases/latest 2>/dev/null \
        | grep "browser_download_url.*linux_${wgcf_arch}" \
        | cut -d '"' -f 4 | head -n 1 || true)

    if [ -z "$wgcf_url" ]; then
        wgcf_url="https://github.com/ViRb3/wgcf/releases/download/v2.2.22/wgcf_2.2.22_linux_${wgcf_arch}"
    fi

    curl -fsSL "$wgcf_url" -o /usr/local/bin/wgcf
    chmod +x /usr/local/bin/wgcf

    mkdir -p /opt/warp-native/wgcf
    pushd /opt/warp-native/wgcf >/dev/null || return 0

    if [ ! -f wgcf-account.toml ]; then
        info "Registering Cloudflare WARP account via wgcf..."
        local attempt=1
        while [ $attempt -le 4 ]; do
            YES=1 /usr/local/bin/wgcf register --accept-tos >/dev/null 2>&1 && break
            sleep 3
            attempt=$((attempt + 1))
        done
    fi

    if [ -f wgcf-account.toml ]; then
        /usr/local/bin/wgcf generate >/dev/null 2>&1 || true
    fi

    if [ -f wgcf-profile.conf ]; then
        sed -i '/^DNS =/d' wgcf-profile.conf
        if ! grep -q "Table = off" wgcf-profile.conf; then
            sed -i '/^MTU =/aTable = off' wgcf-profile.conf
        fi
        if ! grep -q "PersistentKeepalive = 25" wgcf-profile.conf; then
            sed -i '/^Endpoint =/aPersistentKeepalive = 25' wgcf-profile.conf
        fi
        # Normalize IPv4 WARP endpoint and strip IPv6 address if needed
        sed -i 's/,\s*[0-9a-fA-F:]\+\/128//' wgcf-profile.conf
        sed -i '/Address = [0-9a-fA-F:]\+\/128/d' wgcf-profile.conf
        sed -i 's|^Endpoint = .*|Endpoint = 162.159.192.1:2408|' wgcf-profile.conf
        sed -i 's|^AllowedIPs = .*|AllowedIPs = 0.0.0.0/0|' wgcf-profile.conf

        mkdir -p /etc/wireguard
        cp wgcf-profile.conf /etc/wireguard/warp.conf
        chmod 600 /etc/wireguard/warp.conf

        systemctl stop wg-quick@warp >/dev/null 2>&1 || true
        ip link delete warp >/dev/null 2>&1 || true
        systemctl enable --now wg-quick@warp >/dev/null 2>&1 || true

        if ip link show warp >/dev/null 2>&1; then
            ok "Cloudflare WARP interface 'warp' is UP and enabled on boot (Table = off)."
        else
            warn "WARP interface failed to start automatically; check 'systemctl status wg-quick@warp'."
        fi
    else
        warn "Could not generate wgcf profile (Cloudflare API may be rate-limiting). You can retry later."
    fi

    popd >/dev/null || true
}

