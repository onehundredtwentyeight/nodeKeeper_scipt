apply_firewall() {
    if ! command -v ufw >/dev/null 2>&1; then
        return 0
    fi
    ufw allow "${SSH_PORT}/tcp" comment 'SSH' >/dev/null 2>&1 || true
    if [ "$SERVER_DISABLED" = "true" ]; then
        ufw delete allow 80/tcp >/dev/null 2>&1 || true
        ufw delete allow 443/tcp >/dev/null 2>&1 || true
        ufw delete allow 443/udp >/dev/null 2>&1 || true
        if [ -n "$PANEL_IP" ]; then
            ufw delete allow from "$PANEL_IP" to any port "$NODE_PORT" proto tcp >/dev/null 2>&1 || true
        fi
    else
        ufw allow 80/tcp comment 'HTTP' >/dev/null 2>&1 || true
        ufw allow 443/tcp comment 'HTTPS-REALITY' >/dev/null 2>&1 || true
        ufw allow 443/udp comment 'QUIC-Hysteria' >/dev/null 2>&1 || true
        if [ -n "$PANEL_IP" ]; then
            ufw allow from "$PANEL_IP" to any port "$NODE_PORT" proto tcp comment 'Remnawave-Panel' >/dev/null 2>&1 || true
        fi
    fi
    ufw reload >/dev/null 2>&1 || true
}

