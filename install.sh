# ==============================================================================
# Step 8: Deploy Remnanode Stack, Firewall & Maintenance Schedule
# ==============================================================================
deploy_remnanode_and_schedule() {
    step "7/8 Deploying Remnanode (${INSTALL_MODE}) & Configuring Firewall"

    # Configure UFW
    info "Configuring UFW firewall rules..."
    ufw default deny incoming >/dev/null 2>&1 || true
    ufw default allow outgoing >/dev/null 2>&1 || true
    ufw allow "${SSH_PORT}/tcp" comment 'SSH' >/dev/null 2>&1 || true
    ufw allow 80/tcp comment 'HTTP' >/dev/null 2>&1 || true
    ufw allow 443/tcp comment 'HTTPS-REALITY' >/dev/null 2>&1 || true
    ufw allow 443/udp comment 'QUIC-Hysteria' >/dev/null 2>&1 || true
    if [ -n "$PANEL_IP" ]; then
        ufw allow from "$PANEL_IP" to any port "$NODE_PORT" proto tcp comment 'Remnawave-Panel' >/dev/null 2>&1 || true
    fi
    ufw --force enable >/dev/null 2>&1 || true
    ok "UFW firewall enabled (SSH:${SSH_PORT}, 80, 443, and ${NODE_PORT} from ${PANEL_IP})."

    # Deploy containers via nodeKeeper mode switch
    /usr/local/bin/nodeKeeper mode "$INSTALL_MODE"

    step "8/8 Configuring Maintenance Schedule"
    if [ "$MAINT_ENABLED" = "true" ]; then
        /usr/local/bin/nodeKeeper schedule enable
    else
        /usr/local/bin/nodeKeeper schedule disable
    fi
}

