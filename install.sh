generate_maintenance_script() {
    mkdir -p "$NK_DIR" "$NK_LOG_DIR"
    cat > "$NK_MAINT_SCRIPT" <<'EOF'
#!/usr/bin/env bash
export DEBIAN_FRONTEND=noninteractive
NK_DIR="/opt/nodekeeper"
NK_ENV="${NK_DIR}/nodekeeper.env"
LOG_DIR="${NK_DIR}/logs"
mkdir -p "$LOG_DIR"

if [ -f "$NK_ENV" ]; then
    source "$NK_ENV"
fi

MAINT_MIN_DAYS="${MAINT_MIN_DAYS:-5}"
MAINT_MAX_DAYS="${MAINT_MAX_DAYS:-10}"
MAINT_LOGGING="${MAINT_LOGGING:-true}"
MAINT_EXTRA_CMD="${MAINT_EXTRA_CMD:-}"

DATE=$(date +%Y-%m-%d_%H-%M)
if [ "$MAINT_LOGGING" = "true" ]; then
    LOG_FILE="${LOG_DIR}/update_${DATE}.log"
    TEST_LOG="${LOG_DIR}/tests_${DATE}.log"
else
    LOG_FILE="/dev/null"
    TEST_LOG="/dev/null"
fi

{
    echo "=== Maintenance started: $DATE ==="
    if [ -d /opt/remnanode ] && [ -f /opt/remnanode/docker-compose.yml ]; then
        cd /opt/remnanode && /usr/bin/docker compose pull
    fi
    /usr/bin/apt-get update && /usr/bin/apt-get upgrade -y -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold"
    if [ -d /opt/remnanode ] && [ -f /opt/remnanode/docker-compose.yml ] && [ "${SERVER_DISABLED:-false}" != "true" ]; then
        cd /opt/remnanode && /usr/bin/docker compose up -d --build
    fi
    if [ -n "$MAINT_EXTRA_CMD" ]; then
        echo "--- Running custom command: $MAINT_EXTRA_CMD ---"
        eval "$MAINT_EXTRA_CMD"
    fi
    echo "=== Maintenance completed ==="
} >> "$LOG_FILE" 2>&1

if [ "$MAINT_LOGGING" = "true" ]; then
    {
        echo "=== Diagnostics: $DATE ==="
        wget -qO - "https://raw.githubusercontent.com/vernette/ipregion/refs/heads/master/ipregion.sh" | bash
        wget -qO - "https://github.com/vernette/censorcheck/raw/master/censorcheck.sh" | bash
    } >> "$TEST_LOG" 2>&1

    find "$LOG_DIR" -type f -name "*.log" -mtime +30 -delete 2>/dev/null || true
fi

SPAN=$(( MAINT_MAX_DAYS - MAINT_MIN_DAYS + 1 ))
[ "$SPAN" -lt 1 ] && SPAN=1
NEXT_DAYS=$(( ( RANDOM % SPAN ) + MAINT_MIN_DAYS ))
NEXT_HOUR=$(( RANDOM % 24 ))
NEXT_MIN=$(( RANDOM % 60 ))
NEXT_DATE=$(date -d "+${NEXT_DAYS} days" +%d)
NEXT_MONTH=$(date -d "+${NEXT_DAYS} days" +%m)

CRON_JOB="${NEXT_MIN} ${NEXT_HOUR} ${NEXT_DATE} ${NEXT_MONTH} * /bin/bash ${NK_DIR}/maintenance.sh"
(crontab -l 2>/dev/null | grep -v "maintenance.sh"; echo "$CRON_JOB") | crontab -

sleep 10
/usr/sbin/reboot
EOF
    chmod +x "$NK_MAINT_SCRIPT"
}

schedule_enable() {
    generate_maintenance_script
    local span=$(( MAINT_MAX_DAYS - MAINT_MIN_DAYS + 1 ))
    [ "$span" -lt 1 ] && span=1
    local next_days=$(( ( RANDOM % span ) + MAINT_MIN_DAYS ))
    local h=$(( RANDOM % 24 ))
    local m=$(( RANDOM % 60 ))
    local d mon
    d=$(date -d "+${next_days} days" +%d 2>/dev/null || date +%d)
    mon=$(date -d "+${next_days} days" +%m 2>/dev/null || date +%m)
    local job="${m} ${h} ${d} ${mon} * /bin/bash ${NK_MAINT_SCRIPT}"
    (crontab -l 2>/dev/null | grep -v "maintenance.sh"; echo "$job") | crontab -
    MAINT_ENABLED="true"
    save_env
    ok "Maintenance schedule ENABLED (Next run in ~${next_days} days: ${d}.${mon} at $(printf '%02d:%02d' "$h" "$m"))."
}

schedule_disable() {
    (crontab -l 2>/dev/null | grep -v "maintenance.sh") | crontab - 2>/dev/null || true
    MAINT_ENABLED="false"
    save_env
    ok "Maintenance schedule DISABLED."
}

