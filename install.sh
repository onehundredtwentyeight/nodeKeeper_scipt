}

cmd_start() {
    SERVER_DISABLED="false"
    save_env
    apply_firewall
    if [ -f "${REMNA_DIR}/docker-compose.yml" ]; then
        info "Starting containers in ${REMNA_DIR}..."
        (cd "$REMNA_DIR" && docker compose up -d --build --remove-orphans)
        ok "Node services started."
    else
        err "Compose file not found at ${REMNA_DIR}/docker-compose.yml"
    fi
}

cmd_stop() {
    if [ -f "${REMNA_DIR}/docker-compose.yml" ]; then
        info "Stopping containers in ${REMNA_DIR}..."
        (cd "$REMNA_DIR" && docker compose down)
        ok "Node services stopped."
    fi
}

cmd_restart() {
    if [ -f "${REMNA_DIR}/docker-compose.yml" ]; then
        info "Restarting containers in ${REMNA_DIR}..."
        (cd "$REMNA_DIR" && docker compose down && docker compose up -d --build --remove-orphans)
        ok "Node services restarted."
    fi
}

cmd_disable_server() {
    warn "Disabling node services and closing proxy firewall ports..."
    cmd_stop
    SERVER_DISABLED="true"
    save_env
    apply_firewall
    ok "Server is now DISABLED. Run 'nodeKeeper enable' to re-enable."
}

cmd_enable_server() {
    info "Re-enabling node services and restoring firewall rules..."
    cmd_start
    ok "Server is now ENABLED."
}

cmd_switch_mode() {
    local target_mode="${1:-}"
    if [ -z "$target_mode" ]; then
        echo -e "\n${C_BOLD}Select Installation Mode:${C_RESET}"
        echo "  1) basic            — Remnanode only (no Caddy)"
        echo "  2) selfsteal-single — Remnanode + Caddy (one server per domain)"
        echo "  3) selfsteal-multi  — Remnanode + Caddy with Cloudflare DNS plugin (multi-server)"
        read -rp "Enter choice [1-3]: " m_choice
        case "$m_choice" in
            1) target_mode="basic" ;;
            2) target_mode="selfsteal-single" ;;
            3) target_mode="selfsteal-multi" ;;
            *) err "Invalid selection."; return 1 ;;
        esac
    fi

    case "$target_mode" in
        basic|no-caddy) target_mode="basic" ;;
        selfsteal-single|single|selfsteal)
            target_mode="selfsteal-single"
            if [ -z "$SELF_STEAL_DOMAIN" ]; then
                read -rp "Enter Selfsteal Domain (e.g. node.example.com): " SELF_STEAL_DOMAIN
            fi
            ;;
        selfsteal-multi|multi|cloudflare)
            target_mode="selfsteal-multi"
            if [ -z "$SELF_STEAL_DOMAIN" ]; then
                read -rp "Enter Selfsteal Domain (e.g. node.example.com): " SELF_STEAL_DOMAIN
            fi
            if [ -z "$CLOUDFLARE_API_TOKEN" ]; then
                read -rp "Enter Cloudflare API Token (DNS Edit permission): " CLOUDFLARE_API_TOKEN
            fi
            ;;
        *)
            err "Invalid mode '$target_mode'. Use: basic | selfsteal-single | selfsteal-multi"
            return 1
            ;;
    esac

    info "Switching mode to: ${target_mode}..."
    if [ -f "${REMNA_DIR}/docker-compose.yml" ]; then
        (cd "$REMNA_DIR" && docker compose down --remove-orphans) || true
    fi
    INSTALL_MODE="$target_mode"
    save_env
    write_mode_configs "$INSTALL_MODE"
    apply_firewall
    (cd "$REMNA_DIR" && docker compose up -d --build --remove-orphans)
    ok "Successfully switched to mode: ${INSTALL_MODE}"
}

cmd_uninstall() {
    local force="${1:-false}"
    if [ "$force" != "--yes" ]; then
        echo -e "${C_RED}${C_BOLD}WARNING: This will completely uninstall Remnanode, Caddy, maintenance cron jobs, and nodeKeeper configurations!${C_RESET}"
        read -rp "Type 'UNINSTALL' to confirm: " confirm
        if [ "$confirm" != "UNINSTALL" ]; then
            info "Uninstall cancelled."
            return 0
        fi
    fi

    info "Stopping and removing Docker containers, volumes, and images..."
    if [ -d "$REMNA_DIR" ] && [ -f "${REMNA_DIR}/docker-compose.yml" ]; then
        (cd "$REMNA_DIR" && docker compose down -v --rmi local --remove-orphans) || true
    fi
    rm -rf "$REMNA_DIR"

    info "Removing maintenance schedule..."
    (crontab -l 2>/dev/null | grep -v "maintenance.sh") | crontab - 2>/dev/null || true

    info "Stopping WARP interface if present..."
    systemctl disable --now wg-quick@warp >/dev/null 2>&1 || true
    rm -f /etc/wireguard/warp.conf

    info "Cleaning up firewall rules..."
    if command -v ufw >/dev/null 2>&1; then
        ufw delete allow 80/tcp >/dev/null 2>&1 || true
        ufw delete allow 443/tcp >/dev/null 2>&1 || true
        ufw delete allow 443/udp >/dev/null 2>&1 || true
        if [ -n "$PANEL_IP" ]; then
            ufw delete allow from "$PANEL_IP" to any port "$NODE_PORT" proto tcp >/dev/null 2>&1 || true
        fi
        ufw reload >/dev/null 2>&1 || true
    fi

    info "Removing nodeKeeper files..."
    rm -rf "$NK_DIR"
    sed -i '/alias nodeKeeper=/d' /root/.bashrc 2>/dev/null || true
    if [ -n "$ADMIN_USER" ] && [ -f "/home/${ADMIN_USER}/.bashrc" ]; then
        sed -i '/alias nodeKeeper=/d' "/home/${ADMIN_USER}/.bashrc" 2>/dev/null || true
    fi
    rm -f /usr/local/bin/nodeKeeper /usr/local/bin/nodekeeper
    ok "Full uninstallation complete."
}

menu_schedule() {
    while true; do
        echo -e "\n${C_BOLD}=== Maintenance Schedule Control ===${C_RESET}"
        schedule_status
        echo ""
        echo "  1) Enable Maintenance Schedule"
        echo "  2) Disable Maintenance Schedule"
        echo "  3) Change Frequency Range (current: ${MAINT_MIN_DAYS}-${MAINT_MAX_DAYS} days)"
        echo "  4) Toggle Logging (current: ${MAINT_LOGGING})"
        echo "  5) Set Additional Custom Command"
        echo "  6) Run Maintenance Now (Warning: will reboot server!)"
        echo "  0) Back"
        read -rp "Select option: " s_opt
        case "$s_opt" in
            1) schedule_enable ;;
            2) schedule_disable ;;
            3)
                read -rp "Enter minimum days between runs [default 5]: " min_d
                read -rp "Enter maximum days between runs [default 10]: " max_d
                MAINT_MIN_DAYS="${min_d:-5}"
                MAINT_MAX_DAYS="${max_d:-10}"
                [ "$MAINT_MAX_DAYS" -lt "$MAINT_MIN_DAYS" ] && MAINT_MAX_DAYS="$MAINT_MIN_DAYS"
                save_env
                [ "$MAINT_ENABLED" = "true" ] && schedule_enable
                ;;
            4)
                [ "$MAINT_LOGGING" = "true" ] && MAINT_LOGGING="false" || MAINT_LOGGING="true"
                save_env
                generate_maintenance_script
                ok "Maintenance logging set to: ${MAINT_LOGGING}"
                ;;
            5)
                echo "Current extra command: ${MAINT_EXTRA_CMD:-<none>}"
                read -rp "Enter custom command to run during maintenance (leave empty to clear): " extra_c
                MAINT_EXTRA_CMD="$extra_c"
                save_env
                generate_maintenance_script
                ok "Custom maintenance command updated."
                ;;
            6)
                read -rp "Run maintenance now? Server will reboot upon completion! [y/N]: " r_conf
                if [[ "$r_conf" =~ ^[Yy]$ ]]; then
                    generate_maintenance_script
                    bash "$NK_MAINT_SCRIPT"
                fi
                ;;
            0) break ;;
            *) warn "Invalid choice." ;;
        esac
    done
}

